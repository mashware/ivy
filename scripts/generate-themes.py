#!/usr/bin/env python3
"""Generate bundled palette data from the pinned Windows Terminal JSON fixtures."""
import json
import subprocess
from pathlib import Path

root = Path(__file__).resolve().parent.parent
names = {
    "CatppuccinMocha": "Catppuccin Mocha", "CatppuccinLatte": "Catppuccin Latte",
    "Nord": "Nord", "GithubDarkDefault": "GitHub Dark Default",
    "GithubLightDefault": "GitHub Light Default", "RosePine": "Rose Pine",
    "RosePineDawn": "Rose Pine Dawn", "RosePineMoon": "Rose Pine Moon",
}
keys = ["black", "red", "green", "yellow", "blue", "purple", "cyan", "white",
        "brightBlack", "brightRed", "brightGreen", "brightYellow", "brightBlue",
        "brightPurple", "brightCyan", "brightWhite", "background", "foreground", "cursorColor"]
lines = ["// Generated by scripts/generate-themes.py; do not edit by hand.",
         "use super::NamedTheme;", "", "pub(super) fn palette(theme: NamedTheme) -> Option<([u32; 16], u32, u32, u32)> {", "    match theme {"]
for variant, name in names.items():
    data = json.loads((root / "resources/themes" / (name + ".json")).read_text())
    values = ["0x" + data[key].removeprefix("#").lower() for key in keys]
    lines += [f"        NamedTheme::{variant} => Some((", "            [" + ", ".join(values[:8]) + ",", "             " + ", ".join(values[8:16]) + "],", "            " + ", ".join(values[16:]) + ",", "        )),"]
lines += ["        _ => None,", "    }", "}", ""]
(root / "crates/app/src/theme/catalog.rs").write_text("\n".join(lines))
subprocess.run(["rustfmt", "--edition", "2024", str(root / "crates/app/src/theme/catalog.rs")], check=True)
